"""Optional real software-TPM quote to direct core redemption experiment.

This isolated profile does not change the HTTP services' development assurance.
The test CA enrolls an AK generated by the disposable simulator. No manufacturer
provenance, holder-key residency, co-location, or PCR-selection appraisal is
claimed. It uses the released verifier without implementing a TPM wire parser.
"""

